#!/usr/bin/env bash
set -euo pipefail
sudo ln -sf "/usr/share/zoneinfo/$CAGE_TZ" /etc/localtime
printf '%s\n' "$CAGE_TZ" | sudo tee /etc/timezone >/dev/null
if ! locale -a | tr '[:upper:]' '[:lower:]' | grep -qx "${CAGE_LOCALE,,}" && ! locale -a | grep -q "${CAGE_LOCALE%%.*}.utf8"; then
  printf '%s UTF-8\n' "$CAGE_LOCALE" | sudo tee -a /etc/locale.gen >/dev/null
  sudo locale-gen >/dev/null
fi
sudo install -d -m 0755 /etc/workbench
printf 'TZ=%s\nLANG=%s\nLC_ALL=%s\nBROWSER=/usr/local/bin/xdg-open\n' "$CAGE_TZ" "$CAGE_LOCALE" "$CAGE_LOCALE" | sudo tee /etc/workbench/environment >/dev/null
# Only the browser service reads its interface language.
printf 'BROWSER_LANG=%s\n' "$BROWSER_LANG" | sudo tee /etc/workbench/browser.env >/dev/null
sudo update-locale "LANG=$CAGE_LOCALE" "LC_ALL=$CAGE_LOCALE"
set -a
. /etc/workbench/environment
set +a
unset HTTP_PROXY HTTPS_PROXY ALL_PROXY FTP_PROXY NO_PROXY http_proxy https_proxy all_proxy ftp_proxy no_proxy

# Remove only the exact prompt generated by older installers. User prompts stay intact.
python3 - <<'CAGE_SHELL_PROMPT'
import os, stat, tempfile
from pathlib import Path
p = Path.home() / '.zshrc'
if p.is_file() and not p.is_symlink():
    before = p.read_bytes()
    after = b''.join(b'export PS1="%1~%% "\n' if line == b'export PS1="vm:%1~%% "\n' else line
                     for line in before.splitlines(keepends=True))
    if after != before:
        mode = stat.S_IMODE(p.stat().st_mode)
        with tempfile.NamedTemporaryFile(dir=p.parent, prefix='.zshrc.', delete=False) as stream:
            stream.write(after)
            stream.flush()
            os.fsync(stream.fileno())
            staged = stream.name
        try:
            os.chmod(staged, mode)
            os.replace(staged, p)
        except BaseException:
            os.unlink(staged)
            raise
CAGE_SHELL_PROMPT

# Only the scoped installer receives this variable; services load their fixed environment.
if [ -n "${CAGE_INSTALL_PROXY:-}" ]; then
  export http_proxy="$CAGE_INSTALL_PROXY" https_proxy="$CAGE_INSTALL_PROXY" HTTP_PROXY="$CAGE_INSTALL_PROXY" HTTPS_PROXY="$CAGE_INSTALL_PROXY"
fi
